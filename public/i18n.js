export function translateError(message) {
  if (!message) return message;
  if (language !== 'en') {
    if (imageErrors[message]) return imageErrors[message];
    const http = /^Image API returned HTTP (\d+)\. Check the key, model access and base URL\.$/.exec(message);
    return http ? `生图 API 返回 HTTP ${http[1]}，请检查密钥、模型权限和基础地址。` : message;
  }
  if (messages[message]) return messages[message];
  const size = /^请求体超过允许大小（上限 ([0-9.]+) MiB）$/.exec(message);
  if (size) return `Request body is too large (limit: ${size[1]} MiB).`;
  const upstreamSize = /^上游 (.+) 拒绝请求：实际转发 ([0-9.]+) MiB（([0-9]+) 字节）/.exec(message);
  if (upstreamSize) return `Upstream ${upstreamSize[1]} rejected a ${upstreamSize[2]} MiB (${upstreamSize[3]} bytes) request as too large. Compact the conversation, reduce attachments, or start a new chat with a task summary. Raising the gateway limit cannot override the upstream limit.`;
  const upstream = /^上游 (.+) 返回 HTTP (\d+)；请检查密钥、模型权限和接口协议$/.exec(message);
  if (upstream) return `Upstream ${upstream[1]} returned HTTP ${upstream[2]}. Check its key, model access and protocol.`;
  const exit = /^(.+)（退出码 (.+)）$/.exec(message);
  if (exit) return `${messages[exit[1]] || 'Remote execution failed'} (exit code ${exit[2]})`;
  const field = /^(.+) 格式不正确$/.exec(message);
  if (field) return `Invalid ${field[1]} format`;
  const param = /^远程文本桥接暂不支持参数 (.+)$/.exec(message);
  if (param) return `The remote text bridge does not support parameter ${param[1]}.`;
  // Preserve unknown technical details rather than discarding an actionable server error.
  return message;
}

